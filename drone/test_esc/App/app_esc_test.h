/**
 * @file    app_esc_test.h
 * @brief   【测试任务】电调 + DShot 联调用的应用逻辑
 *
 * 【分层职责】只做业务：什么时候发什么值、状态怎么迁移。
 *   它通过 Module 层组帧、通过 Bsp 层发出去，自己【不碰】任何寄存器。
 *
 * 调度方式（由 main.c 负责）：
 *   用 HAL_GetTick() 的时间戳，每 APP_ESC_TEST_PERIOD_MS 调一次本任务。
 */
#pragma once
#include <stdint.h>

/** 调用周期（ms）。1 → 1 kHz，DShot300 一帧 53 µs，余量充足 */
#define APP_ESC_TEST_PERIOD_MS   1u

/**
 * 是否允许进入"转电机"阶段。
 *   0 = 只跑 IDLE + SELFTEST（安全，用来验协议、看波形）
 *   1 = 走完整流程（会真的转电机！上电前必须限流）
 */
#ifndef APP_ESC_TEST_ENABLE_MOTOR
#define APP_ESC_TEST_ENABLE_MOTOR   1
#endif

/** 斜坡目标油门（0..2047；有效油门从 48 起）
 *  ★ 闭环起步必须给够占空比：电调侧 duty = map(input, 47, 2047, minimum_duty_cycle, 2000)，
 *    而 RM2027 固件把 minimum_duty_cycle 钉成 0 ⇒ 油门 120 只有 73/2000 = 3.6% 占空比，
 *    扭矩不足以带起转子（开环台架验证过能转的是 400 ⇒ 353/2000 = 17.6%）。
 *    这也是 AM32 那边 startup_max_duty_cycle = 400 的口径。
 *  ★★ 2026-10-07 晚：**目标是 300**（占空比 12.7%），别低于采样下限。
 *    ① 采样下限（硬约束，实测踩过）：四路 BEMF 的采样必须整条落在导通期内
 *       ⇒ `CCR4(100) + 扫描拍数(~160) < duty × 2665` ⇒ **duty ≥ 约 9.8%**。
 *       踩坑记录：一度把目标降到 200（duty=152 ⇒ 7.6%）低于下限 ⇒ 四路码里的 v0 变回 0
 *       ⇒ 电调拿垃圾信号"假锁相"：内部 ci 稳在 120、遥测报 e_rpm≈16 万，
 *       **而转子根本没转、只轻微抖动**（用户实测确认）。
 *       ⇒ 判"闭环是否真跑"**必须先看 v0 是否≈三相均值**（v0≠0），它比 e_rpm 可信得多。
 *    ② 高占空比那一档（400 ⇒ 17.6%）采样有效、也确实能转，但实测"转得慢 + 一直抖"，
 *       并在占空比爬到顶后 1~2 秒丢相（ci 从 165 暴跳到 4453、e_rpm 掉到 30 后不自恢复）。
 *       原因待查（曾怀疑"ADC 采样率上限"，但那轮的 ci/e_rpm 部分可能是记账假象，需重测）。
 *    ③ 所以先取中间档 300 把"能真转、且能稳"确认下来，再往上逐级试。 */
#ifndef APP_ESC_TEST_RAMP_TARGET
/* ★ 2026-10-10 由 300 改到 500 —— 台架实测：占空比太小 ⇒ 力矩不足 ⇒
 *   转子跟不上闭环命令 ⇒ 每步滑一下 ⇒ 剧烈抖动。
 *   duty = map(input,47,2047,minimum,2000)：300 ⇒ duty 251（12.55%）；
 *                                          500 ⇒ duty 453（22.6%）⇒ 力矩接近翻倍。
 *   ESC 侧起步油门 OL_INPUT_START 已同步改成 500，交棒前后无台阶。 */
/* ★ 2026-10-10 退回 500 —— 拉到 1050 实测会让闭环失步掉出（见下）★★
 *   实测：F1 油门 1050（duty ≈1000）时，t=1.0s 交棒成功后 t=1.5s 又掉回开环启动链
 *   （ol_startup_arm 1→0→1），commutation_interval 出现 5.5e7 这类荒唐值，running 归零
 *   ⇒ 电机失步、闭环丢失。⇒ 高占空比这条路走不通（至少不能这样硬拉）。
 *   退回 500（duty 453），与电调侧一起改"把 ci 地板降下来"的路线。
 *   转速换算更正：机械 RPM = 过零/秒 ÷ 36 × 60 = 过零/秒 × 1.667
 *   （每机械转 36 次换相 = 6 电周期 × 6 极对）—— 之前我按 ×16.67 算，数值大了 10 倍。 */
/* ★ 2026-10-10 还原成 400（与电调侧归档配置一致）★★
 *   电调开环段已还原归档分支的 OL_INPUT_START=400（duty 351），
 *   这里同步回 400 ⇒ 交棒前后都是 duty 351，无台阶，且与"开环能转"的工况一致。 */
#define APP_ESC_TEST_RAMP_TARGET    400u
#endif

/**
 * 上电默认是否"先守零油门"（写进 g_dbg.hold_zero）。见 app_debug.h 里该字段的说明。
 *   1（默认）= 上电后一直发 DISARM(0)，等调试器把 g_dbg.hold_zero 写 0 才爬坡。
 *     好处：不管电调什么时候上电/重烧，它都一定能拿到"连续 1 秒零油门"去解锁；
 *           也顺手避免"一上电电机就自己转"。
 *   0 = 恢复以前"上电 3 秒后自动爬坡"的行为（此时电调若在 F1 之前上电就会解锁失败）。
 */
#ifndef APP_ESC_TEST_HOLD_ZERO_DEFAULT
/* ★ 2026-10-09 改回 1：台架现在按"先守零油门 → 人开电源 → 调试器放行"的顺序做实验。
 *   为什么必须是 1：电调侧解锁要求"油门连续为 0 约 1 秒"，而电源什么时候开由人决定
 *   —— 只有让 F1【一直发 0】等在那儿，才能保证不管电调何时上电都能解锁；
 *   同时"一开电电机就自己转"这件事也被彻底避免（放行权在调试器手里）。
 *   实验步骤：① 复位 F1（本值=1 ⇒ 一直发 DISARM(0)）
 *             ② 确认电调 armed=1、running=0
 *             ③ 人开 12V
 *             ④ 调试器把 g_dbg.hold_zero 写 0 ⇒ F1 立刻进斜坡、电调开始转
 *   改回 0 的行为是"复位后 3 秒自动爬坡"，那样电源时刻就没法控制了。 */
#define APP_ESC_TEST_HOLD_ZERO_DEFAULT  1u
#endif

/** 初始化（清状态、初始化 Bsp 与观测层） */
void app_esc_test_init(void);

/** 周期任务。now_ms 由调用者（main.c）传入 HAL_GetTick() 的时间戳 */
void app_esc_test_task(uint32_t now_ms);
